// All 22 sentence styles and all punctuation marks from the project brief.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createEngine, applyAll } from '../engine/engine.js';

const e = createEngine();
const styles = (t) => e.analyze(t).sentences.flatMap((s) => s.analysis.styles.map((x) => x.type));
const fix = (t) => applyAll(t, e.analyze(t).issues);

const cases = [
 ['العلم أفضل من المال.', 'preference'], ['القاهرة أكبر مدينة في مصر.', 'preference'], ['فاز الفريق بالجائزة الكبرى.', 'preference'],
 ['نحن العرب نكرم الضيف.', 'specification'], ['نحن الطلاب نحترم معلمينا.', 'specification'],
 ['الصدق الصدق!', 'enticement'], ['الصدق والأمانة!', 'enticement'], ['عليك بالصبر.', 'enticement'],
 ['إياك والكذب!', 'warning'], ['الكسل الكسل!', 'warning'], ['احذر النار.', 'warning'],
 ['إن العلم نور.', 'emphasis'], ['لقد نجح المجتهد.', 'emphasis'], ['جاء الطلاب كلهم.', 'emphasis'], ['حضر المدير نفسه.', 'emphasis'], ['والله لأجتهدن.', 'oath'],
 ['أقسم بالله إنه صادق.', 'oath'], ['وامعتصماه!', 'lament'], ['وا أسفاه!', 'lament'],
 ['إنما يخشى الله العلماء.', 'restriction'], ['ما نجح إلا المجتهد.', 'restriction'], ['لم يبق سوى يومين.', 'restriction'],
 ['نجح الطلاب إلا خالدا.', 'exception'], ['حضر الضيوف ما عدا واحدا.', 'exception'],
 ['يا للعلماء للجهلاء!', 'appeal'], ['لعل الفرج قريب.', 'hope'], ['عسى أن ننجح.', 'hope'], ['ليت الشباب يعود يوما.', 'wish'], ['يا ليتني كنت معهم.', 'wish'],
 ['الكتاب قرأته.', 'preoccupation'], ['الدرس فهمناه جيدا.', 'preoccupation'],
];
for (const [t, want] of cases) test(`style ${want}: ${t}`, () => assert.ok(styles(t).includes(want), styles(t).join(',')));

const clean = ['الطالب كتابه جديد.', 'ذهبت إلى السوق واشتريت الخبز.', 'الطلاب غير المجتهدين رسبوا.', 'هذا غير صحيح.', 'إلا أنه تأخر قليلا.', 'كتبت الدرس.'];
for (const t of clean) test(`no style/issue: ${t}`, () => {
  assert.deepEqual(styles(t), ['statement']);
  assert.deepEqual(e.analyze(t).issues.filter((i) => i.severity !== 'hint').map((i) => i.ruleId), []);
});

