// Bundles the engine into gdocs-addon/Engine.html (one <script>), because
// Google Apps Script can't load ES modules. Run: npm run build:gdocs
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'gdocs-addon', 'build');
mkdirSync(out, { recursive: true });
execSync(`npx --yes esbuild@0.28.1 engine/engine.js --bundle --format=iife --global-name=Mudaqqiq --target=es2020 --outfile=gdocs-addon/build/engine.bundle.js --log-level=warning`, { cwd: root, stdio: 'inherit' });
const js = readFileSync(join(out, 'engine.bundle.js'), 'utf8');
writeFileSync(join(root, 'gdocs-addon', 'Engine.html'), `<script>\n// Generated by tools/build-gdocs.mjs from engine/ — do not edit by hand.\n${js.replace(/<\/script/gi, '<\/script')}\n</script>\n`);
console.log('gdocs-addon/Engine.html ready (' + Math.round(js.length / 1024) + ' KB)');
